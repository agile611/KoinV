#!/bin/bash
# Agile611 Koinos RISC-V SBOM Generation Script
# Generates Software Bill of Materials (SPDX) for Agile611 Koinos RISC-V images

set -euo pipefail

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log_info() { echo -e "${GREEN}[INFO]${NC} $*"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*"; }

# Configuration
IMAGE="${1:-}"
OUTPUT_DIR="${2:-/Users/guillem/code/Agile611 Koinos RISC-V/build/sbom}"
VERSION="${VERSION:-$(date -u +%y.%m.%d)}"

mkdir -p "$OUTPUT_DIR"

log_info "=== Agile611 Koinos RISC-V SBOM Generation ==="
echo "Version: $VERSION"
echo "Output: $OUTPUT_DIR"
echo ""

# Check if image provided
if [[ -z "$IMAGE" ]]; then
    # Find latest image
    IMAGE=$(ls -t /Users/guillem/code/Agile611 Koinos RISC-V/build/output/*.img.xz 2>/dev/null | head -1 || true)
    if [[ -z "$IMAGE" ]]; then
        log_error "No image provided or found"
        exit 1
    fi
fi

log_info "Generating SBOM for: $IMAGE"

# Install syft if not present
if ! command -v syft &> /dev/null; then
    log_info "Installing syft..."
    curl -sSfL https://raw.githubusercontent.com/anchore/syft/main/install.sh | sh -s -- -b /usr/local/bin
fi

# Generate SPDX SBOM
SBOM_FILE="$OUTPUT_DIR/sbom-$(date -u +%y.%m.%d).spdx.json"
log_info "Generating SPDX SBOM..."
syft packages "$IMAGE" -o spdx-json > "$SBOM_FILE"

# Generate CycloneDX SBOM
CYCLONEDX_FILE="$OUTPUT_DIR/sbom-$(date -u +%y.%m.%d).cyclonedx.json"
log_info "Generating CycloneDX SBOM..."
syft packages "$IMAGE" -o cyclonedx-json > "$CYCLONEDX_FILE"

# Generate table output for human reading
TABLE_FILE="$OUTPUT_DIR/sbom-$(date -u +%y.%m.%d).table.txt"
syft packages "$IMAGE" -o table > "$TABLE_FILE"

# Validate SPDX
log_info "Validating SPDX..."
if command -v jq &> /dev/null; then
    PACKAGE_COUNT=$(jq '.packages | length' "$OUTPUT_DIR/sbom-$(date -u +%y.%m.%d).spdx.json")
    log_info "SBOM generated with $PACKAGE_COUNT packages"
fi

# Generate summary
cat > "/tmp/sbom-summary-$(date -u +%y.%m.%d).txt" << SUMMARYEOF
Agile611 Koinos RISC-V SBOM Summary
==================
Version: $(date -u +%y.%m.%d)
Image: $(basename $IMAGE)
Generated: $(date -u)
SPDX File: $(basename $SBOM_FILE)
CycloneDX File: $(basename $CYCLONEDX_FILE)
Table File: $(basename $TABLE_FILE)

Package Count: $PACKAGE_COUNT

Key Packages:
- linux-image-riscv64
- glibc
- systemd
- openssl
- busybox
- dropbear
- openssh-server
- kernel modules
- firmware blobs

Generated by: Agile611 Koinos RISC-V SBOM Generator
Date: $(date -u)
SUMMARYEOF

cat /tmp/sbom-summary-$(date -u +%y.%m.%d).txt

log_info "SBOM generation complete"
echo "SPDX: $SBOM_FILE"
echo "CycloneDX: $CYCLONEDX_FILE"
echo "Table: $TABLE_FILE"
